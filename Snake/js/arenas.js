/** Turn a text map into grid data. Throws on malformed maps so mistakes surface early. */
export function parseMap(text) {
  const rows = text.trim().split('\n').map((r) => r.trim());
  const h = rows.length;
  const w = rows[0].length;
  const walls = new Uint8Array(w * h);
  const portals = new Int32Array(w * h).fill(-1);
  const pairs = {};
  let start = -1;
  rows.forEach((row, y) => {
    if (row.length !== w) throw new Error(`Row ${y} is ${row.length} wide, expected ${w}`);
    [...row].forEach((ch, x) => {
      const i = y * w + x;
      if (ch === '#') walls[i] = 1;
      else if (ch === 'S') start = i;
      else if (/[1-4]/.test(ch)) (pairs[ch] ||= []).push(i);
      else if (ch !== '.') throw new Error(`Unknown map character "${ch}" at ${x},${y}`);
    });
  });
  if (start < 0) throw new Error('Map has no start cell');
  const portalPairs = [];
  for (const [id, cells] of Object.entries(pairs)) {
    if (cells.length !== 2) throw new Error(`Portal ${id} needs exactly two cells`);
    portals[cells[0]] = cells[1];
    portals[cells[1]] = cells[0];
    portalPairs.push({ id: Number(id), a: cells[0], b: cells[1] });
  }
  return { w, h, walls, portals, portalPairs, start };
}
