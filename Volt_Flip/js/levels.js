/** Every level in order, with its chapter, id ('2-3'), index and shard target filled in. */
export const LEVELS = CHAPTERS.flatMap((ch) =>
  ch.levels.map((lv, i) => {
    lv.id = `${ch.id}-${i + 1}`;
    lv.chapter = ch;
    lv.number = i + 1;
    return lv;
  }),
);
LEVELS.forEach((lv, i) => (lv.index = i));

export const levelById = (id) => LEVELS.find((lv) => lv.id === id) || null;

/** Shards needed for the shard star, given the level's total. */
export const shardTarget = (level, total) => level.target ?? Math.floor(total * SHARD_SHARE);
